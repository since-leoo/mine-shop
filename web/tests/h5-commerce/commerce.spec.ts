import { expect, test } from '@playwright/test'
import { addresses, addressUrl, assertNoUnexpectedRequests, captureCommerce, confirmUrl, coupon, expectWithinViewport, mockCommerce, secondCoupon, selectedAddressKey } from './helpers'

test('长收件人地址卡片不溢出，默认标签单行且文字垂直居中', async ({ page, baseURL, viewport }) => {
  const api = await mockCommerce(page, baseURL!)
  await page.goto(addressUrl)
  const screen = page.locator('.address-list:visible')
  await expect(screen.locator('.address-list__card')).toHaveCount(2)
  const badge = screen.locator('.address-list__default-badge')
  await expect(badge).toHaveText('默认')
  const geometry = await badge.evaluate(element => {
    const text = element.querySelector('.address-list__default-badge-text')!
    const range = document.createRange()
    range.selectNodeContents(text)
    const rects = Array.from(range.getClientRects()).filter(rect => rect.width > 0)
    const label = range.getBoundingClientRect()
    const box = element.getBoundingClientRect()
    return { lines: new Set(rects.map(rect => Math.round(rect.top))).size, textHeight: label.height, textWidth: label.width, badgeWidth: box.width, fontSize: parseFloat(getComputedStyle(text).fontSize), centerDelta: Math.abs((box.top + box.bottom) / 2 - (label.top + label.bottom) / 2) }
  })
  expect(geometry.lines).toBe(1)
  expect(geometry.textHeight).toBeLessThanOrEqual(geometry.fontSize * 1.6)
  expect(geometry.textWidth).toBeLessThanOrEqual(geometry.badgeWidth)
  expect(geometry.centerDelta).toBeLessThanOrEqual(2)
  await expectWithinViewport(screen.locator('.address-list__card, .address-list__card-header'), viewport!.width)
  const editButton = await screen.locator('.address-list__action-btn--edit').first().boundingBox()
  expect(editButton!.height).toBeGreaterThanOrEqual(44)
  await assertNoUnexpectedRequests(api)
  if (viewport!.width === 320) await captureCommerce(page, 'h5-address-list-long-after-320.png')
})

test('选择模式编辑和删除按钮不误选地址，编辑提交保留字段', async ({ page, baseURL, viewport }) => {
  const api = await mockCommerce(page, baseURL!)
  await page.goto(confirmUrl)
  await page.locator('.order-confirm:visible .address-card').click()
  const list = page.locator('.address-list:visible')
  await expect(list.locator('.address-list__card')).toHaveCount(2)
  await list.locator('.address-list__action-btn--edit').first().click()
  await expect(page).toHaveURL(/address\/edit\/index\?id=11&selectMode=1&isOrderSure=1$/)
  expect(await page.evaluate(key => localStorage.getItem(key), selectedAddressKey)).toBeNull()
  const edit = page.locator('.address-edit:visible')
  await expect(edit.locator('input[placeholder="请输入收货人姓名"]')).toHaveValue(addresses[0].name)
  await expectWithinViewport(edit.locator('.address-edit__form, .address-edit__save-btn'), viewport!.width)
  const textareaStyle = await edit.locator('.address-edit__textarea').evaluate(wrapper => {
    const native = wrapper.matches('textarea') ? wrapper : wrapper.querySelector('textarea')!
    const outer = getComputedStyle(wrapper)
    const inner = getComputedStyle(native)
    return { font: inner.fontFamily, expectedFont: outer.fontFamily, fontSize: inner.fontSize, expectedFontSize: outer.fontSize, color: inner.color, expectedColor: outer.color, resize: inner.resize }
  })
  expect(textareaStyle.font).toBe(textareaStyle.expectedFont)
  expect(textareaStyle.fontSize).toBe(textareaStyle.expectedFontSize)
  expect(textareaStyle.color).toBe(textareaStyle.expectedColor)
  expect(textareaStyle.resize).toBe('none')
  await edit.locator('input[placeholder="请输入收货人姓名"]').fill('陈小明')
  await edit.locator('input[placeholder="街道、楼牌号等"], textarea[placeholder="街道、楼牌号等"]').fill('科技园新楼 603 室')
  await expectWithinViewport(edit.locator('.address-edit__form, .address-edit__save-btn'), viewport!.width)
  if (viewport!.width === 375) await captureCommerce(page, 'h5-address-edit-after-375.png')
  await edit.locator('.address-edit__save-btn').click()
  await expect(page).toHaveURL(/address\/list\/index\?selectMode=1&isOrderSure=1$/)
  await expect(list.locator('.address-list__name').first()).toHaveText('陈小明')
  if (viewport!.width === 375) await captureCommerce(page, 'h5-address-list-after-375.png')
  const update = api.requests.find(item => item.path.endsWith('/addresses/11') && item.method === 'PUT')!
  expect(update.body).toMatchObject({ name: '陈小明', phone: addresses[0].phone, detail: '科技园新楼 603 室', is_default: 1, province_code: '440000', city_code: '440300', district_code: '440305' })
  await list.locator('.address-list__action-btn--delete').last().click()
  await expect(page.getByText('确认删除该地址吗？', { exact: true })).toBeVisible()
  await page.getByText('确定', { exact: true }).click()
  await expect(list.locator('.address-list__card')).toHaveCount(1)
  expect(api.requests.some(item => item.path.endsWith('/addresses/12') && item.method === 'DELETE')).toBe(true)
  expect(await page.evaluate(key => localStorage.getItem(key), selectedAddressKey)).toBeNull()
  await assertNoUnexpectedRequests(api)
})

