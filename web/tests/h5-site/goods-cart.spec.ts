const path = (suffix: string) => '/#/pages/' + suffix

test('商品列表失败重试第一页、价格排序生效且加号进入规格详情', async ({ page, viewport }) => {
  let fail = true
  const api = await goodsApi(page, call => {
    if (call.path === '/api/v1/products' && fail) { fail = false; return { code: 500, message: '稍后重试' } }
  })
  await page.goto(path('goods/list/index?categoryId=7'))
  const screen = page.locator('.goods-list-page:visible')
  await expect(screen.getByText('加载失败', { exact: true })).toBeVisible()
  await expect(screen.getByText('暂无相关商品', { exact: true })).toHaveCount(0)
  await screen.getByText('刷新', { exact: true }).click()
  await expect(screen.locator('.goods-card')).toHaveCount(2)
  expect(api.requests.filter(r => r.path === '/api/v1/products').map(r => r.query.get('page'))).toEqual(['1', '1'])
  await screen.getByText('价格降序', { exact: true }).click()
  await expect(screen.locator('.goods-card__title').first()).toHaveText('高价商品')
  expect(api.requests.at(-1)?.query.get('sort')).toBe('price_desc')
  await screen.getByText('价格升序', { exact: true }).click()
  await expect(screen.locator('.goods-card__title').first()).toHaveText(title)
  await expectWithinViewport(screen.locator('.goods-card, .goods-card__body, .goods-card__down'), viewport!.width)
  await screen.locator('.goods-card__add-cart').first().click()
  await expect(page).toHaveURL(/goods\/details\/index\?spuId=101$/)
  await expect(page.locator('.goods-info__title:visible')).toHaveText(title)
  expectHealthy(api)
})

